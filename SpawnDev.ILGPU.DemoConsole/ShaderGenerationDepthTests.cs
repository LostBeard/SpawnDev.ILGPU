    static string Generate(CapabilityProfile profile)
    {
        var method = typeof(ShaderGenerationDepthTests).GetMethod(nameof(SequentialBranchesKernel), BindingFlags.Static | BindingFlags.NonPublic)!;
        string result = "";
        Exception? error = null;
        var thread = new Thread(() =>
        {
            try { var g = ShaderCompiler.Generate(method, profile); result = g.Source ?? (g.Binary != null ? $"{g.Binary.Length} bytes" : ""); }
            catch (Exception e) { error = e; }
        }, 256 * 1024);
        thread.Start();
        thread.Join();
        if (error != null) throw new Exception($"{profile.Name}: {error.GetType().Name}: {error.Message}", error);
        return result;
    }

