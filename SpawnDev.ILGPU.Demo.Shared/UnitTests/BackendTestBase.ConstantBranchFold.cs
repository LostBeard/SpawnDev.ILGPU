    // A branch on a constant property of a struct TYPE PARAMETER (`if (default(T).Flag)`) must be folded before code
    // generation: its untaken arm may use a feature the device lacks. SpawnDev.ILGPU.ML's GQA softmax (Tuvok 2026-11-09,
    // GgufBatchDecoder.GqaChunkSoftmax<TG, TR> before ML 50270de5) guarded Warp.ShuffleXor + group barriers this way in an
    // [AggressiveInlining] helper; the branch survived to the OpenCL generator ("Subgroup shuffle requires SubGroupShuffle
    // capability" on NVIDIA OpenCL). Mirrors that shape: generic aggressive-inlining helper, loops and barriers in both
    // arms, an explicitly grouped kernel. The runtime pipelines fold it (this test passed before the 5.4.23 change too); the
    // offline ShaderCompiler WebGPU path did not, which the WebGPU / WebGL kernel pipelines' late UCE now covers.
    public abstract partial class BackendTestBase
