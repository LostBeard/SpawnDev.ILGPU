        // Tuvok's failing shape: the branch is in the KERNEL ENTRY method, after enough inlined code to use up the budget,
        // with the shuffles inside loops. Before 5.4.23 the getter stayed a call (budget exhausted), the branch was not
        // folded, and the shuffle reached the OpenCL / WebGL generators.
        static void ConstantBranchAfterBudgetKernel<TR>(Index1D i, ArrayView<int> data) where TR : struct, IConstantBranchFlag
        {
            int v = data[i];
            int bulk = ConstantBranchBulk(v, i) ^ ConstantBranchBulk(v + 1, i) ^ ConstantBranchBulk(v + 2, i);
            if (default(TR).UseShuffle)
            {
                for (int off = 16; off > 0; off >>= 1)
                    v = Math.Max(v, Warp.ShuffleXor(v, off));
            }
            data[i] = v * 3 + (bulk & 1);
        }

