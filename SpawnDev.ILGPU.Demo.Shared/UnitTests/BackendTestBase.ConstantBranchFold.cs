        public interface IConstantBranchFlag { bool UseShuffle { get; } }
        public struct ConstantBranchNoShuffle : IConstantBranchFlag { public bool UseShuffle => false; }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static void ConstantBranchReduce<TR>(ArrayView<int> data, ArrayView<int> scratch, int t, int n) where TR : struct, IConstantBranchFlag
        {
            if (default(TR).UseShuffle)
            {
                int v = data[t];
                for (int s = 1; s < 32; s <<= 1)
                    v += Warp.ShuffleXor(v, s);
                if ((t & 31) == 0) scratch[t >> 5] = v;
                Group.Barrier();
                data[t] = scratch[0] + v;
                Group.Barrier();
            }
            else
            {
                int v = 0;
                for (int k = 0; k < n; k++)
                    v += data[k];
                Group.Barrier();
                data[t] = v + t;
                Group.Barrier();
            }
        }

        static void ConstantBranchFoldKernel<TR>(ArrayView<int> data, ArrayView<int> scratch, int n) where TR : struct, IConstantBranchFlag
        {
            int t = Group.IdxX;
            ConstantBranchReduce<TR>(data, scratch, t, n);
        }

