// ============================================================================
// Float16 Emulation Functions (16-bit IEEE 754 in u32, f32 arithmetic)
// ============================================================================

// Expand a 16-bit Float16 bit pattern (held in the low 16 bits of a u32)
// into a native f32 value. Denormals flush to signed zero.
fn _f16_to_f32(h: u32) -> f32 {
    let sign = (h >> 15u) & 1u;
    let exp  = (h >> 10u) & 0x1Fu;
    let mant = h & 0x3FFu;
    // exp == 0: zero or denormal - flush to signed zero
    if (exp == 0u) {
        return bitcast<f32>(sign << 31u);
    }
    // exp == 31: Inf or NaN - preserve sign, propagate mantissa into f32 NaN/Inf
    if (exp == 31u) {
        return bitcast<f32>((sign << 31u) | (0xFFu << 23u) | (mant << 13u));
    }
    // Normal: rebias exponent (-15 + 127 = +112), shift mantissa (10 -> 23 bits)
    return bitcast<f32>((sign << 31u) | ((exp + 112u) << 23u) | (mant << 13u));
}

// Compress a native f32 into the 16-bit Float16 bit pattern (returned in low 16
// bits of the u32). Underflow clamps to signed zero; overflow clamps to signed
// Inf while preserving mantissa bits so NaNs stay NaN.
fn _f32_to_f16(f: f32) -> u32 {
    // IEEE round-to-nearest-even f32 -> f16, incl subnormals + overflow-to-Inf. Bit-exact to
    // numpy/PyTorch/CUDA/OpenCL and the managed HalfConversion (von der Zijp truncation replaced).
    let bits = bitcast<u32>(f);
    let sign = (bits >> 16u) & 0x8000u;
    let rest = bits & 0x7FFFFFFFu;
    if (rest >= 0x7F800000u) {
        if (rest > 0x7F800000u) { return sign | 0x7E00u; }   // NaN
        return sign | 0x7C00u;                                // Inf
    }
    let e: i32 = i32((rest >> 23u) & 0xFFu) - 127;
    let f32Mant = rest & 0x7FFFFFu;
    if (e > 15) { return sign | 0x7C00u; }                    // overflow -> Inf
    if (e < -14) {
        if (e < -25) { return sign; }                          // -> +-0
        let signif = f32Mant | 0x800000u;
        let shift = u32((-14 - e) + 13);
        var m = signif >> shift;
        let roundBit = (signif >> (shift - 1u)) & 1u;
        let sticky = select(0u, 1u, (signif & ((1u << (shift - 1u)) - 1u)) != 0u);
        if (roundBit == 1u && (sticky == 1u || (m & 1u) == 1u)) { m = m + 1u; }
        return sign | m;
    }
    let mant10 = f32Mant >> 13u;
    let roundB = (f32Mant >> 12u) & 1u;
    let stick = select(0u, 1u, (f32Mant & 0xFFFu) != 0u);
    var outBits = (u32(e + 15) << 10u) | mant10;
    if (roundB == 1u && (stick == 1u || (mant10 & 1u) == 1u)) { outBits = outBits + 1u; }
    return sign | outBits;
}
";

        /// <summary>
        /// WGSL helpers that convert between the 16-bit bfloat16 bit pattern (held in the
        /// low 16 bits of a u32) and f32 at buffer load/store boundaries. bfloat16 is the
        /// top 16 bits of an fp32, so conversion is pure bit-shifting - no exponent rebias
        /// or table. Matches ILGPU.BFloat16's managed ConvertBFloat16ToFloat /
        /// ConvertFloatToBFloat16 (and the Wasm reference) byte-for-byte.
        /// </summary>
        public const string BF16Functions = @"
// ============================================================================
// BFloat16 Emulation Functions (top-16-bits-of-fp32 in u32, f32 arithmetic)
// ============================================================================

// Expand a 16-bit bfloat16 bit pattern (low 16 bits of a u32) into f32 by
// shifting it back into the high half of the fp32 encoding (exact).
fn _bf16_to_f32(h: u32) -> f32 {
    return bitcast<f32>((h & 0xFFFFu) << 16u);
}

// Compress a native f32 into the 16-bit bfloat16 bit pattern (low 16 bits of the
// u32) using round-to-nearest-even. NaN is preserved (a naive truncate could
// collapse some NaNs to Inf, so force a mantissa bit).
fn _f32_to_bf16(f: f32) -> u32 {
    let bits = bitcast<u32>(f);
    if ((bits & 0x7FFFFFFFu) > 0x7F800000u) {
        return ((bits >> 16u) | 0x0040u) & 0xFFFFu;
    }
    let lsb = (bits >> 16u) & 1u;
    let rounded = bits + 0x7FFFu + lsb;
    return (rounded >> 16u) & 0xFFFFu;
}
";

        /// <summary>
        /// FP8 (OCP E5M2 + E4M3FN) bit-conversion helpers. Both FP8 formats are always emulated
        /// (no native WGSL fp8). Direct WGSL ports of the managed ConvertFloat8E*M*ToFloat /
        /// ConvertFloatToFloat8E*M* (CPU-verified idempotence 0/256, and the OpenCL C twins are
        /// PMT-verified) so every representable value round-trips bit-identically. The raw 8-bit
        /// pattern lives in the low 8 bits of a u32; values compute as f32 in-register.
        /// </summary>
        public const string FP8Functions = @"
// ============================================================================
// FP8 Emulation Functions (E5M2 = 1/5/2 bias 15 IEEE-style; E4M3FN = 1/4/3 bias 7, no Inf, sat 448)
// ============================================================================

fn _e5m2_to_f32(raw: u32) -> f32 {
    let bits = raw & 0xFFu;
    let sign = (bits & 0x80u) << 24u;
    let expo = (bits >> 2u) & 0x1Fu;
    let mant = bits & 0x03u;
    if (expo == 0u) {
        if (mant == 0u) { return bitcast<f32>(sign); }
        var e: u32 = 127u - 15u + 1u;
        var m: u32 = mant;
        loop { if ((m & 0x04u) != 0u) { break; } m = m << 1u; e = e - 1u; }
        m = m & 0x03u;
        return bitcast<f32>(sign | (e << 23u) | (m << 21u));
    }
    if (expo == 0x1Fu) { return bitcast<f32>(sign | (0xFFu << 23u) | (mant << 21u)); }
    let f32Exp = expo - 15u + 127u;
    return bitcast<f32>(sign | (f32Exp << 23u) | (mant << 21u));
}

fn _f32_to_e5m2(f: f32) -> u32 {
    let bits = bitcast<u32>(f);
    let sign = (bits >> 24u) & 0x80u;
    let rest = bits & 0x7FFFFFFFu;
    if (rest > 0x7F800000u) { return sign | 0x7Fu; }
    if (rest == 0x7F800000u) { return sign | 0x7Cu; }
    let f32Exp = i32((rest >> 23u) & 0xFFu);
    let f32Mant = rest & 0x7FFFFFu;
    let e = f32Exp - 127;
    if (e > 15) { return sign | 0x7Cu; }
    if (e < -14) {
        if (f32Exp == 0) { return sign; }
        let signif = f32Mant | 0x800000u;
        let shift = (-14 - e) + 21;
        if (shift > 31) { return sign; }
        var m: u32 = signif >> u32(shift);
        let roundBit = (signif >> u32(shift - 1)) & 1u;
        let sticky = select(0u, 1u, (signif & ((1u << u32(shift - 1)) - 1u)) != 0u);
        if (roundBit == 1u && (sticky == 1u || (m & 1u) == 1u)) { m = m + 1u; }
        return sign | (m & 0x03u) | ((m >> 2u) << 2u);
    }
    let mant2 = f32Mant >> 21u;
    let roundB = (f32Mant >> 20u) & 1u;
    let stick = select(0u, 1u, (f32Mant & 0xFFFFFu) != 0u);
    let eField = u32(e + 15);
    var outBits: u32 = (eField << 2u) | mant2;
    if (roundB == 1u && (stick == 1u || (mant2 & 1u) == 1u)) { outBits = outBits + 1u; }
    return sign | (outBits & 0x7Fu);
}

fn _e4m3_to_f32(raw: u32) -> f32 {
    let bits = raw & 0xFFu;
    let sign = (bits & 0x80u) << 24u;
    let expo = (bits >> 3u) & 0x0Fu;
    let mant = bits & 0x07u;
    if ((bits & 0x7Fu) == 0x7Fu) { return bitcast<f32>(sign | 0x7FC00000u); }
    if (expo == 0u) {
        if (mant == 0u) { return bitcast<f32>(sign); }
        var e: u32 = 127u - 7u + 1u;
        var m: u32 = mant;
        loop { if ((m & 0x08u) != 0u) { break; } m = m << 1u; e = e - 1u; }
        m = m & 0x07u;
        return bitcast<f32>(sign | (e << 23u) | (m << 20u));
    }
    let f32Exp = expo - 7u + 127u;
    return bitcast<f32>(sign | (f32Exp << 23u) | (mant << 20u));
}

fn _f32_to_e4m3(f: f32) -> u32 {
    let bits = bitcast<u32>(f);
    let sign = (bits >> 24u) & 0x80u;
    let rest = bits & 0x7FFFFFFFu;
    if (rest >= 0x7F800000u) { return sign | 0x7Fu; }
    let f32Exp = i32((rest >> 23u) & 0xFFu);
    let f32Mant = rest & 0x7FFFFFu;
    let e = f32Exp - 127;
    if (e > 8) { return sign | 0x7Fu; } // fn: e>8 unconditional overflow -> NaN; e==8 rounds below
    if (e < -6) {
        if (f32Exp == 0) { return sign; }
        let signif = f32Mant | 0x800000u;
        let shift = (-6 - e) + 20;
        if (shift > 31) { return sign; }
        var m: u32 = signif >> u32(shift);
        let roundBit = (signif >> u32(shift - 1)) & 1u;
        let sticky = select(0u, 1u, (signif & ((1u << u32(shift - 1)) - 1u)) != 0u);
        if (roundBit == 1u && (sticky == 1u || (m & 1u) == 1u)) { m = m + 1u; }
        return sign | (m & 0x7Fu);
    }
    let mant3 = f32Mant >> 20u;
    let roundB = (f32Mant >> 19u) & 1u;
    let stick = select(0u, 1u, (f32Mant & 0x7FFFFu) != 0u);
    let eField = u32(e + 7);
    var outBits: u32 = (eField << 3u) | mant3;
    if (roundB == 1u && (stick == 1u || (mant3 & 1u) == 1u)) { outBits = outBits + 1u; }
    if (outBits >= 0x7Fu) { outBits = 0x7Fu; } // fn: full outBits (incl 0x80 carry) reaching the 0x7F slot -> NaN
    return sign | (outBits & 0x7Fu);
}
";

        /// <summary>
        /// FP4 (OCP E2M1FN) bit-conversion helpers. Always emulated (no native WGSL fp4).
        /// Direct WGSL port of the managed ConvertFloat4E2M1ToFloat / ConvertFloatToFloat4E2M1
        /// (CPU-verified bit-exact to ml_dtypes.float4_e2m1fn; the OpenCL C twins
        /// _e2m1_bits_to_f32 / _f32_to_e2m1_bits are PMT-verified) so every representable value
        /// round-trips bit-identically. 16 finite codes, NO Inf, NO NaN; magnitudes
        /// {0,.5,1,1.5,2,3,4,6}, max 6. The 4-bit value lives in the LOW NIBBLE of an 8-bit
        /// storage element; the raw byte sits in the low 8 bits of a u32. Sign = bit 3 (0x8).
        /// finite overflow AND +-Inf saturate to +-6 (0x7/0xF); NaN -> -0 (0x8).
        /// </summary>
        public const string FP4Functions = @"
// ============================================================================
// FP4 Emulation Functions (E2M1FN = 1/2/1 bias 1; no Inf/NaN; mags {0,.5,1,1.5,2,3,4,6}; value in low nibble)
// ============================================================================

fn _e2m1_to_f32(raw: u32) -> f32 {
    let code = raw & 0x0Fu;
    let sign = (code & 0x8u) << 28u;
    let e = (code >> 1u) & 0x3u;
    let m = code & 0x1u;
    if (e == 0u) {
        if (m == 0u) { return bitcast<f32>(sign); }
        return bitcast<f32>(sign | (126u << 23u)); // subnormal 0.5
    }
    let f32Exp = e - 1u + 127u;
    return bitcast<f32>(sign | (f32Exp << 23u) | (m << 22u));
}

fn _f32_to_e2m1(f: f32) -> u32 {
    let bits = bitcast<u32>(f);
    let sign = (bits >> 28u) & 0x8u;
    let rest = bits & 0x7FFFFFFFu;
    if (rest > 0x7F800000u) { return 0x8u; }          // NaN -> -0
    if (rest >= 0x7F800000u) { return sign | 0x7u; }  // +-Inf -> +-6
    let f32Exp = i32((rest >> 23u) & 0xFFu);
    let f32Mant = rest & 0x7FFFFFu;
    let e = f32Exp - 127;
    if (e > 2) { return sign | 0x7u; }                // finite overflow -> +-6
    if (e < 0) {
        if (f32Exp == 0) { return sign; }             // +-0
        let signif = f32Mant | 0x800000u;
        let shift = (-1 - e) + 23;
        if (shift > 31) { return sign; }              // underflow -> +-0
        var q: u32 = signif >> u32(shift);
        let roundBit = (signif >> u32(shift - 1)) & 1u;
        let sticky = select(0u, 1u, (signif & ((1u << u32(shift - 1)) - 1u)) != 0u);
        if (roundBit == 1u && (sticky == 1u || (q & 1u) == 1u)) { q = q + 1u; }
        return sign | (q & 0x7u);
    }
    let mant1 = f32Mant >> 22u;
    let round = (f32Mant >> 21u) & 1u;
    let stick = select(0u, 1u, (f32Mant & 0x1FFFFFu) != 0u);
    let eField = u32(e + 1);
    var outBits: u32 = (eField << 1u) | mant1;
    if (round == 1u && (stick == 1u || (mant1 & 1u) == 1u)) { outBits = outBits + 1u; }
    if (outBits > 0x7u) { outBits = 0x7u; }           // carry past +-6 saturates (no larger finite/Inf)
    return sign | (outBits & 0x7u);
}
";

