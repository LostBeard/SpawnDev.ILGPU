// NaN by f32 bit pattern (exp == 0xFF && mantissa != 0) and force the
// IEEE result for ordered comparisons.
fn _f32_is_nan_bits(v: f32) -> bool {
    let bits = bitcast<u32>(v);
    return ((bits & 0x7F800000u) == 0x7F800000u) && ((bits & 0x007FFFFFu) != 0u);
}

