// Left shift (0 <= shift < 64)
fn i64_shl(a: emu_i64, shift: u32) -> emu_i64 {
    if (shift == 0u) { return a; }
    if (shift >= 64u) { return emu_i64(0u, 0u); }
    if (shift >= 32u) {
        return emu_i64(0u, a.x << (shift - 32u));
    }
    let lo = a.x << shift;
    let hi = (a.y << shift) | (a.x >> (32u - shift));
    return emu_i64(lo, hi);
